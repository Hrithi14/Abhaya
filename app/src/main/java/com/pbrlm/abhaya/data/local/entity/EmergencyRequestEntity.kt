package com.pbrlm.abhaya.data.local.entity

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.pbrlm.abhaya.domain.model.EmergencyPriority
import com.pbrlm.abhaya.domain.model.EmergencyRequest
import com.pbrlm.abhaya.domain.model.EmergencyStatus
import com.pbrlm.abhaya.domain.model.EmergencyType
import com.pbrlm.abhaya.domain.model.MedicalEmergencyType
import com.pbrlm.abhaya.domain.model.WaterDepth
import java.util.Date

@Entity(tableName = "emergency_requests")
data class EmergencyRequestEntity(
    @PrimaryKey
    val emergencyRequestId: String,
    val userId: String,
    val hazardId: String? = null,
    val clusterId: String? = null,
    val zoneId: String? = null,
    val emergencyType: String,
    val latitude: Double,
    val longitude: Double,
    val gpsAccuracy: Float,
    val timestampMillis: Long,
    val numberOfPeople: Int,
    val children: Boolean,
    val elderly: Boolean,
    val disabled: Boolean,
    val peopleTrapped: Boolean,
    val injured: Boolean,
    val medicalRequired: Boolean,
    val waterDepth: String? = null,
    val waterLevel: String? = null,
    val waterRising: Boolean? = null,
    val medicalEmergencyType: String? = null,
    val personUnconscious: Boolean,
    val breathingProblem: Boolean,
    val severeBleeding: Boolean,
    val pregnancyRelated: Boolean,
    val description: String,
    val buildingFloor: String? = null,
    val contactNumber: String,
    val photoUrl: String? = null,
    val priority: String,
    val status: String,
    val assignedResponderId: String? = null,
    val responderContact: String? = null,
    val responseTimeMillis: Long? = null,
    val resolutionTimeMillis: Long? = null,
    val responderNotes: String? = null,
    val escalationRequired: Boolean,
    val isDemoData: Boolean
) {
    fun toDomain(): EmergencyRequest = EmergencyRequest(
        emergencyRequestId = emergencyRequestId,
        userId = userId,
        hazardId = hazardId,
        clusterId = clusterId,
        zoneId = zoneId,
        emergencyType = EmergencyType.fromString(emergencyType),
        latitude = latitude,
        longitude = longitude,
        gpsAccuracy = gpsAccuracy,
        timestamp = Date(timestampMillis),
        numberOfPeople = numberOfPeople,
        children = children,
        elderly = elderly,
        disabled = disabled,
        peopleTrapped = peopleTrapped,
        injured = injured,
        medicalRequired = medicalRequired,
        waterDepth = waterDepth?.let { WaterDepth.fromString(it) },
        waterLevel = waterLevel,
        waterRising = waterRising,
        medicalEmergencyType = medicalEmergencyType?.let { MedicalEmergencyType.fromString(it) },
        personUnconscious = personUnconscious,
        breathingProblem = breathingProblem,
        severeBleeding = severeBleeding,
        pregnancyRelated = pregnancyRelated,
        description = description,
        buildingFloor = buildingFloor,
        contactNumber = contactNumber,
        photoUrl = photoUrl,
        priority = EmergencyPriority.fromString(priority),
        status = EmergencyStatus.fromString(status),
        assignedResponderId = assignedResponderId,
        responderContact = responderContact,
        responseTime = responseTimeMillis?.let { Date(it) },
        resolutionTime = resolutionTimeMillis?.let { Date(it) },
        responderNotes = responderNotes,
        escalationRequired = escalationRequired,
        isDemoData = isDemoData
    )
}

fun EmergencyRequest.toEntity(): EmergencyRequestEntity = EmergencyRequestEntity(
    emergencyRequestId = emergencyRequestId,
    userId = userId,
    hazardId = hazardId,
    clusterId = clusterId,
    zoneId = zoneId,
    emergencyType = emergencyType.name,
    latitude = latitude,
    longitude = longitude,
    gpsAccuracy = gpsAccuracy,
    timestampMillis = timestamp.time,
    numberOfPeople = numberOfPeople,
    children = children,
    elderly = elderly,
    disabled = disabled,
    peopleTrapped = peopleTrapped,
    injured = injured,
    medicalRequired = medicalRequired,
    waterDepth = waterDepth?.name,
    waterLevel = waterLevel,
    waterRising = waterRising,
    medicalEmergencyType = medicalEmergencyType?.name,
    personUnconscious = personUnconscious,
    breathingProblem = breathingProblem,
    severeBleeding = severeBleeding,
    pregnancyRelated = pregnancyRelated,
    description = description,
    buildingFloor = buildingFloor,
    contactNumber = contactNumber,
    photoUrl = photoUrl,
    priority = priority.name,
    status = status.name,
    assignedResponderId = assignedResponderId,
    responderContact = responderContact,
    responseTimeMillis = responseTime?.time,
    resolutionTimeMillis = resolutionTime?.time,
    responderNotes = responderNotes,
    escalationRequired = escalationRequired,
    isDemoData = isDemoData
)
